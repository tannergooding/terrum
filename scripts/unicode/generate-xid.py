"""Regenerate the pinned Unicode 17 identifier property tables.

Run from the repository root: python scripts/unicode/generate-xid.py
"""

import hashlib
import pathlib
import urllib.request

URL = "https://www.unicode.org/Public/17.0.0/ucd/DerivedCoreProperties.txt"
SHA256 = "24c7fed1195c482faaefd5c1e7eb821c5ee1fb6de07ecdbaa64b56a99da22c08"
OUTPUT = pathlib.Path("sources/Terrum.CodeAnalysis/Lexing/UnicodeXid.cs")


def ranges(data, property_name):
    values = []
    for line in data.decode("utf-8").splitlines():
        fields = line.split("#", 1)[0].split(";")
        if len(fields) != 2 or fields[1].strip() != property_name:
            continue
        endpoints = fields[0].strip().split("..")
        start = int(endpoints[0], 16)
        end = int(endpoints[-1], 16)
        if values and start <= values[-1][1] + 1:
            values[-1] = (values[-1][0], end)
        else:
            values.append((start, end))
    if not values:
        raise ValueError(f"No {property_name} ranges in UCD")
    return values


def main():
    data = urllib.request.urlopen(URL).read()
    if hashlib.sha256(data).hexdigest() != SHA256:
        raise ValueError("Unicode input checksum mismatch")
    output = [
        "// Generated by scripts/unicode/generate-xid.py from Unicode 17.0.0",
        "// DerivedCoreProperties.txt (SHA-256 " + SHA256 + ").",
        "// Unicode License V3: see THIRD-PARTY-NOTICES.md.",
        "namespace Terrum.CodeAnalysis.Lexing;",
        "",
        "internal static class UnicodeXid",
        "{",
        "    internal static bool IsStart(int scalar) => Contains(StartRanges, scalar);",
        "    internal static bool IsContinue(int scalar) => Contains(ContinueRanges, scalar);",
        "",
        "    private static bool Contains(System.ReadOnlySpan<int> ranges, int scalar)",
        "    {",
        "        var low = 0;",
        "        var high = (ranges.Length / 2) - 1;",
        "        while (low <= high)",
        "        {",
        "            var middle = low + ((high - low) / 2);",
        "            if (scalar < ranges[2 * middle])",
        "            {",
        "                high = middle - 1;",
        "            }",
        "            else if (scalar > ranges[(2 * middle) + 1])",
        "            {",
        "                low = middle + 1;",
        "            }",
        "            else",
        "            {",
        "                return true;",
        "            }",
        "        }",
        "        return false;",
        "    }",
    ]
    for name in ("Start", "Continue"):
        output += ["", f"    private static System.ReadOnlySpan<int> {name}Ranges => ["]
        for start, end in ranges(data, f"XID_{name}"):
            output.append(f"        0x{start:X}, 0x{end:X},")
        output.append("    ];")
    output += ["}", ""]
    OUTPUT.write_text("\n".join(output), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
